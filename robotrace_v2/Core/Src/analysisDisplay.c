/////////////////////////////////////////////////////////////////////
// モジュール名 analysisDisplayNumber
// 処理概要     固定桁の非負整数を文字列へ書き、桁あふれは最大表示へ飽和する
// 引数         text: 出力先、digits: 桁数、value: 表示値
// 戻り値       なし
/////////////////////////////////////////////////////////////////////
static void analysisDisplayNumber(char *text, uint8_t digits, uint32_t value)
{
    uint32_t remaining = value;
    for (uint8_t i = digits; i > 0U; i--) {
        text[i - 1U] = (char)('0' + remaining % 10U);
        remaining /= 10U;
    }
    if (remaining != 0U) {
        for (uint8_t i = 0U; i < digits; i++) text[i] = '9';
    }
}

/////////////////////////////////////////////////////////////////////
// モジュール名 analysisDisplayBegin
// 処理概要     手動・自動解析共通の待機画面を準備し、連続転送を停止する
// 引数         mode: 解析モード名、logNumber: 解析対象ログ番号
// 戻り値       なし
/////////////////////////////////////////////////////////////////////
void analysisDisplayBegin(const char *mode, int16_t logNumber)
{
    active = modeDSP && initLCD && patternTrace == 0U && !modeLOG;
    if (!active) return;
    startedMs = HAL_GetTick();
    firstFrame = true;
    displayedSeconds = UINT32_MAX;
    progressStage = NULL;
    displayedStage = NULL;
    progressLine = 0U;
    resumeContinuous = ssd1306_IsDMARunning();
    ssd1306_StopDMA(); // 送信中のページは完了させる。待機も強制中断もしない。
    ssd1306_FillRectangle(0, 15, 127, 63, Black);
    ssd1306_SetCursor(34, 16);
    ssd1306_WriteString("Analyzing", Font_6x8, White);
    ssd1306_SetCursor(34, 28);
    ssd1306_printf(Font_6x8, "%.15s", mode);
    ssd1306_SetCursor(34, 38);
    ssd1306_printf(Font_6x8, "Log %05d", logNumber);
    analysisDisplayPoll();
}

/////////////////////////////////////////////////////////////////////
// モジュール名 analysisDisplayProgress
// 処理概要     SLIPの段階と行数を保持し、次の画面更新で表示する
// 引数         stage: 寿命が解析終了まで続く段階名、lineNo: 読込行数
// 戻り値       なし
/////////////////////////////////////////////////////////////////////
void analysisDisplayProgress(const char *stage, uint32_t lineNo)
{
    progressStage = stage;
    progressLine = lineNo;
}

/////////////////////////////////////////////////////////////////////
// モジュール名 analysisDisplayPoll
// 処理概要     メイン側のSD転送待ち・候補探索の区切りで、待機せず表示を更新する
// 引数         なし
// 戻り値       なし
/////////////////////////////////////////////////////////////////////
void analysisDisplayPoll(void)
{
    if (!active) return;
    uint32_t now = HAL_GetTick();
    if ((!firstFrame && now - displayedMs < ANALYSIS_DISPLAY_FRAME_MS) ||
        !ssd1306_IsReadyForSingleUpdate()) return;
    uint32_t elapsed = now - startedMs; // HAL tickの周回を許容する。
    uint8_t frame = (uint8_t)(((elapsed % ANALYSIS_DISPLAY_CYCLE_MS) * 16U) / ANALYSIS_DISPLAY_CYCLE_MS);
    ssd1306_FillRectangle(1, 27, 25, 53, Black);
    ssd1306_DrawBitmap(1, 28, ringFrames[frame], 24, 24, White);
    // 最大999分59秒。値が変わった秒だけ整数で描画する。
    uint32_t seconds = elapsed / 1000U;
    if (seconds > 59999U) seconds = 59999U;
    if (seconds != displayedSeconds) {
        char timeText[] = "000:00";
        analysisDisplayNumber(timeText, 3U, seconds / 60U);
        analysisDisplayNumber(timeText + 4, 2U, seconds % 60U);
        ssd1306_SetCursor(34, 48);
        ssd1306_WriteString(timeText, Font_6x8, White);
        displayedSeconds = seconds;
    }
    if (progressStage != NULL && (progressStage != displayedStage || progressLine != displayedLine)) {
        char text[] = "                     ";
        uint8_t i = 0U;
        while (i < 14U && progressStage[i] != '\0') { text[i] = progressStage[i]; i++; }
        analysisDisplayNumber(text + 15, 5U, progressLine);
        ssd1306_SetCursor(0, 56);
        ssd1306_WriteString(text, Font_6x8, White);
        displayedStage = progressStage;
        displayedLine = progressLine;
    }
    if (ssd1306_UpdateScreenOnce_DMA()) {
        displayedMs = now;
        firstFrame = false;
    }
}

/////////////////////////////////////////////////////////////////////
// モジュール名 analysisDisplayEnd
// 処理概要     解析画面の更新を終了し、元の連続画面転送へ待機せず復帰する
// 引数         なし
// 戻り値       なし
/////////////////////////////////////////////////////////////////////
void analysisDisplayEnd(void)
{
    if (!active) return;
    active = false;
    if (resumeContinuous) ssd1306_ResumeDMA();
}
